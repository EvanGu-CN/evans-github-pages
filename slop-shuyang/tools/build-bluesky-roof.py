"""Project reviewed roof pixels; never replace the building source or infer a ground court."""
from pathlib import Path
import json, math, runpy, subprocess, hashlib
from shapely.geometry import Polygon

ROOT=Path(__file__).resolve().parents[1]
traces=json.loads((ROOT/'tools/data/shuyang/bluesky-roof-traces.json').read_text(encoding='utf-8'))
invert=runpy.run_path(str(ROOT/'tools/china-coordinates.py'))['gcj02_to_wgs84']
pixels=2**traces['imagery']['zoom']*256
kx=111320*math.cos(math.radians(34.1285));ky=110574
def world(p):
    x=traces['imagery']['tileOrigin'][0]*256+p[0];y=traces['imagery']['tileOrigin'][1]*256+p[1]
    lon,lat=invert(x/pixels*360-180,math.degrees(math.atan(math.sinh(math.pi*(1-2*y/pixels)))))
    return [round((lon-118.774)*kx,3),round((34.1285-lat)*ky,3)]
geo=json.loads(subprocess.check_output(['node','--input-type=module','-e',"import {GEO} from './js/shuyang-geodata.js';console.log(JSON.stringify(GEO.mapBuildings.find(b=>b.id==='way/1321791084')));"],cwd=ROOT,text=True,encoding='utf-8'))
source=Polygon(list(zip(geo['o'][::2],geo['o'][1::2])))
out={k:v for k,v in traces.items() if not k.endswith('Pixels')}
for name in ['pavilion','terrace','darkPanel']:
    ring=[world(p) for p in traces[name+'Pixels']];poly=Polygon(ring)
    assert poly.is_valid and source.covers(poly),name
    out[name]=ring
terrace=Polygon(out['terrace'])
out['beds']=[];out['bedClipping']=[]
for ring in traces['bedPixels']:
    raw=Polygon([world(p) for p in ring]);assert raw.is_valid
    bed=raw.intersection(terrace).difference(Polygon(out['darkPanel']).buffer(.2,join_style=2))
    assert bed.geom_type=='Polygon' and bed.area/raw.area>.85
    out['beds'].append([list(p) for p in list(bed.exterior.coords)[:-1]])
    out['bedClipping'].append({'rawAreaM2':round(raw.area,3),'retainedAreaM2':round(bed.area,3)})
assert terrace.covers(Polygon(out['darkPanel']))
assert not Polygon(out['pavilion']).intersects(terrace)
out['traceSha256']=hashlib.sha256((ROOT/'tools/data/shuyang/bluesky-roof-traces.json').read_bytes().replace(b'\r\n',b'\n')).hexdigest()
(ROOT/'js/bluesky-roof-data.js').write_text('// Generated by tools/build-bluesky-roof.py; third-party imagery is not published.\nexport const BLUESKY_ROOF='+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
print(json.dumps({'pavilionAreaM2':round(Polygon(out['pavilion']).area,3),'terraceAreaM2':round(terrace.area,3),'bedAreaM2':round(sum(Polygon(b).area for b in out['beds']),3)},indent=2))
