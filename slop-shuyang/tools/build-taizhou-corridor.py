"""Standard-section display strips; source roads/buildings remain reserved."""
from pathlib import Path
import subprocess,json,hashlib
from shapely import set_precision
from shapely.geometry import Polygon,LineString,Point,box
from shapely.ops import unary_union

ROOT=Path(__file__).resolve().parents[1]
command="import {GEO} from './js/shuyang-geodata.js';import {TAIZHOU_ROAD_REVIEW as review} from './js/road-photo-references.js';process.stdout.write(JSON.stringify({GEO,review,roadJSON:JSON.stringify(GEO.roads)}));"
data=json.loads(subprocess.check_output(['node','--input-type=module','-e',command],cwd=ROOT,text=True,encoding='utf-8'))
geo,review=data['GEO'],data['review'];main=[geo['roads'][r['index']] for r in geo['roadReviews'] if r['reviewId']==review['id']]
assert len(main)==3
def points(flat):return list(zip(flat[::2],flat[1::2]))
def shape(p):return Polygon(points(p['outer']),[points(h) for h in p.get('holes',[])])
def snap(g):return set_precision(g,.001)
main_line=unary_union([LineString(points(r[6])) for r in main])
extent=main_line.buffer(42).bounds;window=box(*extent)
roads=[];junctions=[]
for name,kind,width,lanes,direction,bridge,flat in geo['roads']:
    if bridge:continue
    line=LineString(points(flat))
    if not line.intersects(window):continue
    roads.append(line.buffer(width/2,cap_style=2,join_style=2))
    if name in review['mainNames']:continue
    for a,b in zip(points(flat),points(flat)[1:]):
        cross=abs(b[0]-a[0])>abs(b[1]-a[1])*.7
        junctions.append(LineString([a,b]).buffer(width/2+(8 if cross else .6),cap_style=2))
buildings=[Polygon(points(b['o']),[points(h) for h in b.get('holes',[])]) for b in geo['mapBuildings']]
buildings=[b.buffer(.25,join_style=2) for b in buildings if b.intersects(window)]
water=[Polygon(points(p['rings'][0]),[points(h) for h in p['rings'][1:]]) for p in geo['water']['polygons']]
reserved=[shape(p) for s in geo['urban']['surfaces'] if s['kind']!='green' for p in s['polygons'] if shape(p).intersects(window)]
occupied=snap(unary_union(roads+junctions+buildings+water))
green_mask=snap(unary_union([occupied,*reserved]))
configs=[('side-green',10.85,14.65),('cycleway',14.85,19.15),('landscape',19.35,39.8),('walkway',21,23.5),
         ('curb',10.76,10.94),('cycle-curb',14.65,14.82),('outer-curb',19.16,19.33)]
raw={}
for kind,v0,v1 in configs:
    strips=[]
    for r in main:
        ps=points(r[6])
        for a,b in zip(ps,ps[1:]):
            dx,dz=b[0]-a[0],b[1]-a[1];length=(dx*dx+dz*dz)**.5
            if length<.01:continue
            nx,nz=-dz/length,dx/length
            for side in [-1,1]:
                strips.append(Polygon([(x+nx*v*side,z+nz*v*side) for (x,z),v in [(a,v0),(b,v0),(b,v1),(a,v1)]]))
    raw[kind]=snap(unary_union(strips)).difference(green_mask if kind=='landscape' else occupied)
raw['landscape']=raw['landscape'].difference(unary_union([raw['walkway'],raw['cycle-curb'],raw['outer-curb']]).buffer(.01,join_style=2))
def polygons(g):
    if g.geom_type=='Polygon':return[g]
    return [p for child in getattr(g,'geoms',[]) for p in polygons(child)]
def encode(p):
    flatten=lambda r:[round(v,3) for xy in list(r.coords)[:-1] for v in xy]
    return {'outer':flatten(p.exterior),'holes':[flatten(h) for h in p.interiors]}
surfaces=[{'kind':kind,'polygons':[encode(p) for p in polygons(g) if p.area>.02]} for kind,g in raw.items()]
areas={kind:round(g.area,2) for kind,g in raw.items()}
trees=[]
for road in main:
    ps=points(road[6])
    for a,b in zip(ps,ps[1:]):
        dx,dz=b[0]-a[0],b[1]-a[1];length=(dx*dx+dz*dz)**.5
        if length<1:continue
        nx,nz=-dz/length,dx/length
        for distance in range(9,int(length),17):
            for side in [-1,1]:
                for offset in [26,38]:
                    x=a[0]+dx*distance/length+nx*offset*side;z=a[1]+dz*distance/length+nz*offset*side
                    if not raw['landscape'].covers(Point(x,z).buffer(1.35)):continue
                    trees.append({'x':round(x,3),'z':round(z,3),'y':.245,'scale':.72,'species':len(trees)%2,'tier':1})
result={'reviewId':review['id'],'coordinates':'source WGS84 world metres','captureDate':None,'extent':extent,
        'sourceRoadsDigest':hashlib.sha256(data['roadJSON'].encode()).hexdigest(),
        'limits':'Standard section along mapped centre lines. Paving colours, planting and junction exclusions are display estimates. Existing service roads, buildings (+0.25 m), water and mapped non-green surfaces are reserved.',
        'areaByKind':areas,'surfaces':surfaces,'treeSites':trees}
(ROOT/'js/taizhou-corridor-data.js').write_text('// Generated by tools/build-taizhou-corridor.py. No third-party imagery.\nexport const TAIZHOU_CORRIDOR='+json.dumps(result,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
print(json.dumps({'surfaces':[{'kind':s['kind'],'polygons':len(s['polygons'])} for s in surfaces],'areaByKind':areas,'treeCandidates':len(trees)},indent=2))
