"""Trace only reviewed frontage bands; retain all source road/building geometry."""
from pathlib import Path
import json, math, runpy, subprocess, hashlib
from shapely.geometry import Polygon, LineString, Point, box
from shapely.ops import unary_union
from shapely import set_precision

ROOT=Path(__file__).resolve().parents[1]
traces=json.loads((ROOT/'tools/data/shuyang/cultural-street-traces.json').read_text(encoding='utf-8'))
raw=subprocess.check_output(['node','--input-type=module','-e',"import {GEO} from './js/shuyang-geodata.js';import {CULTURAL_HALLS} from './js/cultural-hall-layout.js';import {ART_GALLERY,galleryDisplayFootprints} from './js/art-gallery-layout.js';console.log(JSON.stringify({GEO,roadJSON:JSON.stringify(GEO.roads),replaceIds:[...CULTURAL_HALLS.map(h=>h.sourceId),ART_GALLERY.sourceId],display:[...CULTURAL_HALLS,galleryDisplayFootprints()].flat()}));"],cwd=ROOT,text=True,encoding='utf-8')
data=json.loads(raw);geo=data['GEO']
invert=runpy.run_path(str(ROOT/'tools/china-coordinates.py'))['gcj02_to_wgs84']
pixels=2**traces['imagery']['zoom']*256;kx=111320*math.cos(math.radians(34.1285));ky=110574
def world(p):
    x=traces['imagery']['tileOrigin'][0]*256+p[0];y=traces['imagery']['tileOrigin'][1]*256+p[1]
    lon,lat=invert(x/pixels*360-180,math.degrees(math.atan(math.sinh(math.pi*(1-2*y/pixels)))))
    return ((lon-118.774)*kx,(34.1285-lat)*ky)
def points(flat):return list(zip(flat[::2],flat[1::2]))
def shape(p):return Polygon(points(p['outer']),[points(h) for h in p.get('holes',[])])
def polygons(g):
    if g.geom_type=='Polygon':return [g]
    return [p for child in getattr(g,'geoms',[]) for p in polygons(child)]
def encode(p):
    flat=lambda r:[round(v,3) for xy in list(r.coords)[:-1] for v in xy]
    return {'outer':flat(p.exterior),'holes':[flat(h) for h in p.interiors]}
fronts=[{**f,'walk':Polygon([world(p) for p in f['walkway']]),'plant':Polygon([world(p) for p in f['green']])} for f in traces['frontages']]
window=unary_union([f[k] for f in fronts for k in ['walk','plant']]).envelope.buffer(8)
roads=[]
for r in geo['roads']:
    if r[5]:continue
    line=LineString(points(r[6]))
    if line.intersects(window):roads.append(line.buffer((r[2]+.8)/2+.3,cap_style=2,join_style=2))
# The museum/library sources include their forecourts. Use their actual display
# bodies here; the layouts subtract these new strips from their old paving.
buildings=[Polygon(points(b['o']),[points(h) for h in b.get('holes',[])]) for b in geo['mapBuildings'] if b['id'] not in data['replaceIds']]
buildings += [Polygon([(p['x'],p['z']) for p in b['outer']], [[(p['x'],p['z']) for p in h] for h in b.get('holes',[])]) for b in data['display']]
water=[Polygon(points(p['rings'][0]),[points(h) for h in p['rings'][1:]]) for p in geo['water']['polygons']]
old=[shape(p) for s in geo['urban']['surfaces'] if s['kind'] not in ['green','plaza','residential-ground'] for p in s['polygons'] if shape(p).intersects(window)]
occupied=unary_union(roads+[b.buffer(.3,join_style=2) for b in buildings if b.intersects(window)]+water+old)
surfaces=[];trees=[];audits=[]
for f in fronts:
    walk=set_precision(f['walk'].difference(occupied),.001)
    plant=set_precision(f['plant'].difference(occupied).difference(walk.buffer(.02)),.001)
    # Thin upper stone strip stays inside the traced walkway, with no new curb
    # crossing a driveway. It is omitted wherever clipping splits that strip.
    curb=walk.boundary.buffer(.09,cap_style=2,join_style=2).intersection(walk)
    for kind,g in [('walkway',walk.difference(curb)),('curb',curb),('green',plant)]:
        surfaces.append({'road':f['name'],'kind':kind,'polygons':[encode(p) for p in polygons(g) if p.area>.015]})
    line=LineString([world(p) for p in f['treeAxis']])
    for distance in range(5,int(line.length),11):
        p=line.interpolate(distance)
        if plant.covers(p.buffer(.65)):
            trees.append({'x':round(p.x,3),'z':round(p.y,3),'y':.245,'scale':.65,'species':0,'tier':1})
    a,b=list(line.coords);length=line.length
    audits.append({'road':f['name'],'sourceWayIds':f['sourceWayIds'],'axis':[round(a[0],3),round(a[1],3),(b[0]-a[0])/length,(b[1]-a[1])/length],'walkwayArea':round(walk.area,3),'greenArea':round(plant.area,3),
                   'rawArea':round(f['walk'].area+f['plant'].area,3),'clippedArea':round(f['walk'].area+f['plant'].area-walk.area-plant.area,3)})
out={**{k:v for k,v in traces.items() if k!='frontages'},'frontages':audits,'extent':list(window.bounds),'sourceRoadsDigest':hashlib.sha256(data['roadJSON'].encode()).hexdigest(),
     'surfaces':surfaces,'treeSites':trees}
(ROOT/'js/cultural-streets-data.js').write_text('// Generated by tools/build-cultural-streets.py; third-party photographs are not bundled.\nexport const CULTURAL_STREETS='+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
print(json.dumps({'frontages':audits,'treeCandidates':len(trees),'polygons':sum(len(s['polygons']) for s in surfaces)},ensure_ascii=False,indent=2))
