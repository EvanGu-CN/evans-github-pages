"""Trace the visible coloured frontage; clip against the actual road ribbon triangles."""
from pathlib import Path
import json,math,runpy,subprocess,hashlib
from shapely.geometry import Polygon
from shapely.ops import unary_union
from shapely import set_precision
ROOT=Path(__file__).resolve().parents[1]
traces=json.loads((ROOT/'tools/data/shuyang/core-junction-frontage-traces.json').read_text(encoding='utf-8'))
data=json.loads(subprocess.check_output(['node','--input-type=module','-e',"import {GEO} from './js/shuyang-geodata.js';import {roadRibbonTriangles} from './js/road-ribbon.js';console.log(JSON.stringify({GEO,roadJSON:JSON.stringify(GEO.roads),triangles:GEO.roads.filter(r=>!r[5]).flatMap(r=>roadRibbonTriangles(Array.from({length:r[6].length/2},(_,i)=>({x:r[6][2*i],z:r[6][2*i+1]})),r[2]).map(t=>t.map(p=>[p.x,p.z])))}));"],cwd=ROOT,text=True,encoding='utf-8'))
invert=runpy.run_path(str(ROOT/'tools/china-coordinates.py'))['gcj02_to_wgs84'];geo=data['GEO'];imagery=traces['imagery'];pixels=2**imagery['zoom']*256
kx=111320*math.cos(math.radians(34.1285));ky=110574
def world(p):
    x=imagery['tileOrigin'][0]*256+p[0];y=imagery['tileOrigin'][1]*256+p[1]
    lon,lat=invert(x/pixels*360-180,math.degrees(math.atan(math.sinh(math.pi*(1-2*y/pixels)))))
    return ((lon-118.774)*kx,(34.1285-lat)*ky)
flatpoints=lambda r:list(zip(r[::2],r[1::2]))
blue=Polygon([world(p) for p in traces['blueOuter']+traces['blueInner'][::-1]])
red=Polygon([world(p) for p in traces['redOuter']+traces['blueOuter'][::-1]])
assert blue.is_valid and red.is_valid
window=blue.union(red).envelope.buffer(3)
roads=unary_union([Polygon(t) for t in data['triangles'] if Polygon(t).intersects(window)]).buffer(.35,join_style=2)
buildings=unary_union([Polygon(flatpoints(b['o']),[flatpoints(h) for h in b.get('holes',[])]) for b in geo['mapBuildings'] if Polygon(flatpoints(b['o'])).intersects(window)]).buffer(1.5,join_style=2)
water=unary_union([Polygon(flatpoints(p['rings'][0]),[flatpoints(h) for h in p['rings'][1:]]) for p in geo['water']['polygons']])
occupied=unary_union([roads,buildings,water])
blueClean=set_precision(blue.difference(occupied),.001);redClean=set_precision(red.difference(occupied).difference(blueClean.buffer(.015)),.001)
def polygons(g):
    if g.geom_type=='Polygon':return [g]
    return [p for c in getattr(g,'geoms',[]) for p in polygons(c)]
def encode(p):
    coords=lambda r:[round(v,3) for xy in list(r.coords)[:-1] for v in xy]
    return {'outer':coords(p.exterior),'holes':[coords(r) for r in p.interiors]}
# A thin material joint is kept inside the blue area, never a new raised curb.
joint=blueClean.boundary.buffer(.065,join_style=2).intersection(blueClean)
surfaces=[{'kind':kind,'polygons':[encode(p) for p in polygons(g) if p.area>.015]} for kind,g in [('blue',blueClean.difference(joint)),('red',redClean),('joint',joint)]]
audit={'rawBlueAreaM2':round(blue.area,3),'rawRedAreaM2':round(red.area,3),'blueAreaM2':round(blueClean.area,3),'redAreaM2':round(redClean.area,3),'removedAreaM2':round(blue.area+red.area-blueClean.area-redClean.area,3),
       'roadOverlapM2':round(blueClean.union(redClean).intersection(roads).area,6),'buildingOverlapM2':round(blueClean.union(redClean).intersection(buildings).area,6)}
assert audit['roadOverlapM2']==0 and audit['buildingOverlapM2']==0
assert blueClean.area>100 and redClean.area>100
out={k:v for k,v in traces.items() if k not in ['blueOuter','blueInner','redOuter']}
out.update({'extent':list(window.bounds),'height':.33,'sourceRoadsDigest':hashlib.sha256(data['roadJSON'].encode()).hexdigest(),
            'traceSha256':hashlib.sha256((ROOT/'tools/data/shuyang/core-junction-frontage-traces.json').read_bytes().replace(b'\r\n',b'\n')).hexdigest(),'surfaces':surfaces,'audit':audit})
(ROOT/'js/core-junction-frontage-data.js').write_text('// Generated by tools/build-core-junction-frontage.py; reference photographs are not bundled.\nexport const CORE_JUNCTION_FRONTAGE='+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
print(json.dumps(audit,indent=2))
